/* assemble the full parts list: family builders + every component, deduped, criticals flagged */
function buildParts(famKey, o) {
  var rng = RNG("parts:" + famKey + ":" + String(o.seed) + ":" + String(o.customHash || ""));
  var bases = o._bases || [{ k: famKey, o: o }];
  var parts = [];
  bases.forEach(function (b) {
    var key = (b.k === "custom") ? (b.o.baseFam || "universal") : b.k;
    var fn = PART_BUILDERS[key] || PART_BUILDERS.universal;
    parts = parts.concat(fn(rng, b.o));
    parts = parts.concat(compParts(rng, b.o));
  });
  var seen = {}, out = [];
  parts.forEach(function (p) {
    var nrm = String(p.name).toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
    if (!seen[nrm]) { seen[nrm] = 1; out.push(p); }
  });
  var crits = CRIT[famKey] || CRIT[(o.baseFam || "")] || [];
  out.forEach(function (p) {
    if (p.critical) return;
    var nm = String(p.name).toLowerCase();
    for (var i = 0; i < crits.length; i++) if (nm.indexOf(crits[i]) >= 0) { p.critical = true; break; }
  });
  return out;
}

/* piece-by-piece assembly order, grouped by phase, then a verification step */
var PHASE_TITLES = { 1: "Structure", 2: "Systems", 3: "Integration", 4: "Finish" };
function buildSteps(famKey, parts, o) {
  var steps = [], n = 0;
  [1, 2, 3, 4].forEach(function (ph) {
    var ps = parts.filter(function (p) { return p.phase === ph; });
    if (!ps.length) return;
    n++;
    steps.push({
      n: n, phase: PHASE_TITLES[ph],
      title: "Step " + n + " — " + PHASE_TITLES[ph] + ": fit " + ps.length + " part group" + (ps.length > 1 ? "s" : ""),
      detail: ps.map(function (p) {
        return "Install " + p.qty + "× " + p.name + " — " + p.material + " — " + p.dims + " — tolerance " + p.tolerance +
          (p.critical ? " — ★ CRITICAL: verify to tolerance before proceeding" : "") + (p.note ? " (" + p.note + ")" : "");
      }).join(" "),
      parts: ps.map(function (p) { return p.name; })
    });
  });
  n++;
  var critNames = parts.filter(function (p) { return p.critical; }).map(function (p) { return p.name; });
  steps.push({
    n: n, phase: "Verification",
    title: "Step " + n + " — Verification: test the complete build",
    detail: "Final check: " + o.how_to_use +
      (critNames.length ? " Confirm every ★ CRITICAL part (" + critNames.join("; ") + ") is seated and torqued to its listed tolerance before first use." : ""),
    parts: []
  });
  return steps;
}

/* cross-references: engine-type piece-by-piece builds + filed archive records */
function buildCrosslinks(famKey, o) {
  var L = [];
  var base = (famKey === "custom") ? (o.baseFam || "universal") : famKey;
  var ENG = { jet: 1, car: 1, engine: 1, "mix-jet-engine": 1, "mix-car-engine": 1 };
  if (ENG[base] || ENG[famKey]) {
    var es = 1 + (hashStr(String(o.id)) % 300);
    L.push({
      kind: "engine-build",
      label: "Piece-by-piece engine build — JAH-GEN-ENGINE-" + ("000000" + es).slice(-6),
      url: GEN_HOME_URL + "?gen=engine-" + es,
      note: "The engine-type build for this design, solved piece by piece with every part, tolerance, and assembly step."
    });
  }
  if (base === "engine" || famKey === "engine") {
    L.push({ kind: "generator", label: "Jet × Engine Mix Lab", url: GEN_HOME_URL + "?fam=mix-jet-engine", note: "This engine class co-designed into a jet airframe." });
    L.push({ kind: "generator", label: "Car × Engine Mix Lab", url: GEN_HOME_URL + "?fam=mix-car-engine", note: "This engine class co-designed into a car chassis." });
  }
  var refs = FILED_REFS[base] || FILED_REFS[famKey] || { specs: [], patents: [] };
  (refs.specs || []).forEach(function (s) {
    L.push({ kind: "filed-spec", label: s[0], title: s[1], url: SPEC_ARCHIVE_URL + s[0],
      note: "Filed Signature archive record — how the Signature system documents this class of build." });
  });
  (refs.patents || []).forEach(function (p) {
    L.push({ kind: "filed-patent", label: p[0], title: p[1], url: PATENT_ARCHIVE_URL + encodeURIComponent(p[0]),
      note: "Filed public patent record — reference for this class of build." });
  });
  return L;
}

function finalize(famKey, o) {
  o.parts = buildParts(famKey, o);
  o.build_steps = buildSteps(famKey, o.parts, o);
  o.crosslinks = buildCrosslinks(famKey, o);
  if (o._bases) delete o._bases;
  return o;
}

